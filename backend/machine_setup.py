"""Post-login machine setup: NIC/BT/serial discovery + Kismet conf + container restart."""

from __future__ import annotations

import json
import os
import re
import subprocess
from pathlib import Path
from typing import Any

from db import get_setting, set_setting
from paths import DATA

MACHINE_JSON = DATA / "machine.json"
KISMET_CONF = DATA / "kismet" / "kismet_site.conf"
SETUP_FLAG = "machine_setup_complete"

_IFACE_RE = re.compile(r"^[A-Za-z0-9_.:-]{1,32}$")
_DEV_RE = re.compile(r"^/dev/[A-Za-z0-9_/.-]{1,64}$")


def machine_setup_complete() -> bool:
    return (get_setting(SETUP_FLAG) or "").strip() in ("1", "true", "yes")


def load_machine_config() -> dict[str, Any]:
    if MACHINE_JSON.is_file():
        try:
            data = json.loads(MACHINE_JSON.read_text(encoding="utf-8"))
            if isinstance(data, dict):
                return data
        except (OSError, json.JSONDecodeError):
            pass
    return {
        "wifi_iface": "",
        "bluetooth_iface": "",
        "gps_device": "",
        "kismet_user": os.getenv("KISMET_USER") or "wardrivrr",
        "kismet_password": os.getenv("KISMET_PASSWORD") or "changeme",
        "httpd_bind": "0.0.0.0",
    }


def kismet_credentials() -> tuple[str, str]:
    cfg = load_machine_config()
    user = (cfg.get("kismet_user") or os.getenv("KISMET_USER") or "wardrivrr").strip()
    password = (
        cfg.get("kismet_password") or os.getenv("KISMET_PASSWORD") or "changeme"
    )
    return user, str(password)


def list_network_interfaces() -> list[dict[str, str]]:
    """Host interfaces (needs network_mode: host)."""
    out: list[dict[str, str]] = []
    try:
        proc = subprocess.run(
            ["ip", "-o", "link", "show"],
            capture_output=True,
            text=True,
            timeout=10,
        )
    except (OSError, subprocess.TimeoutExpired):
        return out
    if proc.returncode != 0:
        return out
    for line in proc.stdout.splitlines():
        # 2: wlan0: <BROADCAST,MULTICAST,UP,...>
        parts = line.split(":", 2)
        if len(parts) < 2:
            continue
        name = parts[1].strip().split("@", 1)[0]
        if not name or name == "lo":
            continue
        flags = parts[2] if len(parts) > 2 else ""
        kind = "other"
        low = name.lower()
        if low.startswith(("wlan", "wlp", "wlx", "kismon")) or "ieee802.11" in flags.lower():
            kind = "wifi"
        elif low.startswith(("eth", "en")):
            kind = "ethernet"
        # Skip docker/bridge noise in the picker
        if low.startswith(("docker", "br-", "veth", "virbr", "cni")):
            continue
        out.append({"name": name, "kind": kind, "raw": line.strip()[:200]})
    return out


def list_bluetooth_adapters() -> list[dict[str, str]]:
    out: list[dict[str, str]] = []
    sys_hci = Path("/sys/class/bluetooth")
    if sys_hci.is_dir():
        for p in sorted(sys_hci.iterdir()):
            if p.name.startswith("hci"):
                out.append({"name": p.name, "path": str(p)})
    if out:
        return out
    try:
        proc = subprocess.run(
            ["hciconfig"],
            capture_output=True,
            text=True,
            timeout=10,
        )
        for line in (proc.stdout or "").splitlines():
            if line.startswith("hci"):
                name = line.split(":", 1)[0].strip()
                if name:
                    out.append({"name": name, "path": f"/sys/class/bluetooth/{name}"})
    except (OSError, subprocess.TimeoutExpired):
        pass
    return out


def list_serial_devices() -> list[dict[str, str]]:
    out: list[dict[str, str]] = []
    for pattern in ("/dev/ttyUSB*", "/dev/ttyACM*", "/dev/ttyAMA*", "/dev/gps*"):
        for path in sorted(Path("/dev").glob(Path(pattern).name)):
            out.append({"name": path.name, "path": str(path)})
    return out


def _safe_iface(value: str, *, optional: bool = False) -> str:
    v = (value or "").strip()
    if not v:
        if optional:
            return ""
        raise ValueError("interface required")
    if not _IFACE_RE.match(v):
        raise ValueError(f"invalid interface name: {v!r}")
    return v


def _safe_dev(value: str) -> str:
    v = (value or "").strip()
    if not v:
        return ""
    if not _DEV_RE.match(v):
        raise ValueError(f"invalid device path: {v!r}")
    return v


def render_kismet_conf(cfg: dict[str, Any]) -> str:
    user = (cfg.get("kismet_user") or "wardrivrr").strip() or "wardrivrr"
    password = str(cfg.get("kismet_password") or "changeme")
    bind = (cfg.get("httpd_bind") or "0.0.0.0").strip() or "0.0.0.0"
    wifi = (cfg.get("wifi_iface") or "").strip()
    bt = (cfg.get("bluetooth_iface") or "").strip()
    gps_dev = (cfg.get("gps_device") or "").strip()

    lines = [
        "# Generated by wardrivrr Machine setup — do not edit by hand",
        "server_name=wardrivrr",
        f"httpd_bind_address={bind}",
        "httpd_port=2501",
        f"httpd_username={user}",
        f"httpd_password={password}",
        "",
        "gps=gpsd:host=127.0.0.1,port=2947",
        "",
    ]
    if wifi:
        lines.append(f"source={wifi}:name=MonitorWifi:type=linuxwifi")
    if bt:
        lines.append(f"source={bt}:name=linuxbt:type=linuxbluetooth")
    if not wifi and not bt:
        lines.append("# No RF sources selected yet")
    if gps_dev:
        lines.append(f"# preferred gps device hint: {gps_dev}")
    lines.extend(
        [
            "",
            "log_prefix=/home/kismet/logs/wardrivrr",
            "log_types=kismet,kis_db",
            "log_title_timestamp=true",
            "",
            "channel_hop=true",
            "channel_hop_speed=5/sec",
            "retry_on_source_error=true",
            "",
        ]
    )
    return "\n".join(lines)


def _docker(args: list[str], *, timeout: int = 180) -> subprocess.CompletedProcess[str]:
    return subprocess.run(
        ["docker", *args],
        capture_output=True,
        text=True,
        timeout=timeout,
    )


def _compose_up_kismet() -> dict[str, Any]:
    """Start/recreate kismet via the same compose project as this API container."""
    try:
        insp = _docker(
            [
                "inspect",
                "-f",
                "{{index .Config.Labels \"com.docker.compose.project.working_dir\"}}"
                "|{{index .Config.Labels \"com.docker.compose.project.config_files\"}}"
                "|{{index .Config.Labels \"com.docker.compose.project\"}}",
                "wardrivrr_api",
            ]
        )
    except (OSError, subprocess.TimeoutExpired) as exc:
        return {"ok": False, "method": "compose", "error": str(exc)}

    parts = (insp.stdout or "").strip().split("|")
    workdir = (parts[0] if parts else "").strip()
    configs = (parts[1] if len(parts) > 1 else "").strip()
    project = (parts[2] if len(parts) > 2 else "").strip() or "wardrivrr"
    if not workdir or not Path(workdir).is_dir():
        return {
            "ok": False,
            "method": "compose",
            "error": f"compose working_dir unknown ({workdir!r})",
        }

    cmd = ["compose", "--project-directory", workdir]
    if project:
        cmd.extend(["-p", project])
    for cfg in configs.split(","):
        cfg = cfg.strip()
        if cfg:
            cmd.extend(["-f", cfg])
    # Recreate so new kismet_site.conf bind is picked up
    cmd.extend(["up", "-d", "--force-recreate", "kismet"])
    env = {k: str(v) for k, v in os.environ.items() if v is not None}
    # Prefer host data path so compose volume interpolation matches the original stack
    host_data = (os.getenv("HOST_DATA_ROOT") or "").strip()
    if not host_data:
        try:
            from valhalla_prep import _host_data_root

            host_data = str(_host_data_root())
        except Exception:
            host_data = ""
    if host_data:
        env["DATA_ROOT"] = host_data
    try:
        proc = subprocess.run(
            ["docker", *cmd],
            capture_output=True,
            text=True,
            timeout=180,
            env=env,
            cwd=workdir,
        )
    except (OSError, subprocess.TimeoutExpired) as exc:
        return {"ok": False, "method": "compose", "error": str(exc)}
    return {
        "ok": proc.returncode == 0,
        "method": "compose",
        "code": proc.returncode,
        "err": (proc.stderr or proc.stdout or "")[-500:],
        "cmd": cmd,
        "DATA_ROOT": host_data or None,
    }


def _ensure_kismet() -> dict[str, Any]:
    """Restart Kismet if present; otherwise compose up the kismet service."""
    steps: list[dict[str, Any]] = []
    for args in (
        ["restart", "wardrivrr_kismet"],
        ["start", "wardrivrr_kismet"],
    ):
        try:
            proc = _docker(args, timeout=120)
        except (OSError, subprocess.TimeoutExpired) as exc:
            steps.append({"cmd": args, "ok": False, "error": str(exc)})
            continue
        steps.append(
            {
                "cmd": args,
                "ok": proc.returncode == 0,
                "err": (proc.stderr or "")[-300:],
            }
        )
        if proc.returncode == 0:
            return {"ok": True, "method": args[0], "container": "wardrivrr_kismet", "steps": steps}

    composed = _compose_up_kismet()
    composed["steps"] = steps
    return composed


def apply_machine_setup(body: dict[str, Any]) -> dict[str, Any]:
    wifi = _safe_iface(str(body.get("wifi_iface") or ""), optional=True)
    bt = _safe_iface(str(body.get("bluetooth_iface") or ""), optional=True)
    gps = _safe_dev(str(body.get("gps_device") or ""))
    user = (str(body.get("kismet_user") or "wardrivrr")).strip() or "wardrivrr"
    password = str(body.get("kismet_password") or "")
    prev = load_machine_config()
    if not password:
        password = str(prev.get("kismet_password") or "")
    if len(password) < 4:
        raise ValueError("kismet_password must be at least 4 characters")
    bind = (str(body.get("httpd_bind") or "0.0.0.0")).strip() or "0.0.0.0"

    cfg = {
        "wifi_iface": wifi,
        "bluetooth_iface": bt,
        "gps_device": gps,
        "kismet_user": user,
        "kismet_password": password,
        "httpd_bind": bind,
    }

    DATA.mkdir(parents=True, exist_ok=True)
    KISMET_CONF.parent.mkdir(parents=True, exist_ok=True)
    MACHINE_JSON.write_text(json.dumps(cfg, indent=2) + "\n", encoding="utf-8")
    KISMET_CONF.write_text(render_kismet_conf(cfg), encoding="utf-8")
    set_setting(SETUP_FLAG, "1")

    restart = _ensure_kismet()
    return {
        "ok": True,
        "config": {**cfg, "kismet_password": "***"},
        "kismet_conf": str(KISMET_CONF),
        "restart": restart,
        "complete": True,
    }


def setup_status_payload() -> dict[str, Any]:
    cfg = load_machine_config()
    return {
        "complete": machine_setup_complete(),
        "config": {
            **cfg,
            "kismet_password": "***" if cfg.get("kismet_password") else "",
            "has_password": bool(cfg.get("kismet_password")),
        },
        "nics": list_network_interfaces(),
        "bluetooth": list_bluetooth_adapters(),
        "serial": list_serial_devices(),
    }
